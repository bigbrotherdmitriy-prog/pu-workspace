from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol


class AnswerProvider(Protocol):
    def answer(self, text: str) -> str: ...


@dataclass(frozen=True)
class ApprovedKnowledgeProvider:
    """Deterministic answers based only on approved sales materials."""

    def answer(self, text: str) -> str:
        query = text.casefold()
        if any(word in query for word in ("цена", "стоимость", "тариф", "сколько стоит")):
            return (
                "PU Workspace доступен как самостоятельная лицензионная версия без обязательного "
                "сопровождения. Стоимость зависит от состава передаваемых прав и релиза. "
                "Оставьте заявку — мы покажем продукт и зафиксируем состав поставки."
            )
        if any(word in query for word in ("безопас", "конфиден", "данные", "защит")):
            return (
                "PU Workspace проектируется с ролями, аудитом и подтверждением значимых действий. "
                "Целевая архитектура поддерживает облачное и частное размещение, а политика AI может "
                "запрещать передачу документов внешней модели. Конкретный контур согласуется на пилоте."
            )
        if any(word in query for word in ("google", "яндекс", "microsoft", "vk", "интеграц")):
            return (
                "PU Workspace не привязан к одному поставщику. Google Workspace сейчас используется "
                "как референсный набор подключений; Яндекс 360, VK WorkSpace, Microsoft и корпоративные "
                "системы относятся к расширяемому roadmap и могут подключаться через адаптеры."
            )
        if any(word in query for word in ("что умеет", "возможност", "функци", "делает")):
            return (
                "PU Workspace объединяет проектный контекст, документы, договоры, задачи и коммуникации. "
                "AI Secretary выделяет важное, предлагает задачи и проекты ответов. Значимые внешние "
                "действия выполняются только по правилам и после подтверждения."
            )
        if any(word in query for word in ("кому", "строит", "подряд", "проектир", "девелоп")):
            return (
                "Первый фокус: строительные, проектные, подрядные и девелоперские организации, где много "
                "договоров, документов, сроков и переписки. Архитектура продукта не ограничена строительством."
            )
        if any(word in query for word in ("готов", "работает", "запущ", "релиз")):
            return (
                "PU Workspace имеет готовую самостоятельную лицензионную версию. Покупателю передаётся "
                "конкретный проверенный релиз с кодом, тестами и документацией; будущие версии и "
                "сторонние аккаунты в поставку не входят."
            )
        return (
            "Я отвечаю по утверждённым материалам PU Workspace. Выберите раздел в меню или опишите "
            "вашу задачу — я покажу подходящий сценарий и помогу запросить лицензионное предложение."
        )
